//Programa For multiplos 

// Estrutura de repetição FOR

for (let i = 1; i <= 400; i++) {

    // Verifica se o número é divisível por 5
    // O operador % calcula o resto da divisão
    // Se o resto for 0, então é múltiplo de 5
    if (i % 5 === 0) {

        // Exibe o número no terminal
        console.log(i);
    }
}
