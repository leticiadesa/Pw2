//Maior que  >
let a = 10;
let b = 5;

console.log(a > b); // true

//

//Menor que <
console.log(a < b); // false

//

//Maior ou igual >=
console.log(a >= 10); // true

//

//Menor ou igual <=
console.log(b <= 5); // true

//

//Igual == e ===
let x = 10;

console.log(x == "10");  // true (compara só o valor)
console.log(x === "10"); // false (compara valor e tipo)

//

//Diferente != e !==
console.log(a != b);   // true
console.log(a !== "10"); // true (tipo diferente)